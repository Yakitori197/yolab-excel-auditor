import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { analyzeWorkbook } from '../analyze';
import { decodeCsvBuffer, parseCsvText, parseXlsx } from '../workbook/parseWorkbook';

function sampleBytes(name: string): Uint8Array {
  return readFileSync(fileURLToPath(new URL(`../../../samples/${name}`, import.meta.url)));
}

function ruleIds(fileName: string): Set<string> {
  const workbook = parseXlsx(sampleBytes(fileName), fileName, 0);
  return new Set(analyzeWorkbook(workbook).findings.map((f) => f.ruleId));
}

describe('demo samples (generated by samples/generate-samples.mjs)', () => {
  it('good-inventory.xlsx is clean and scores highly', () => {
    const workbook = parseXlsx(sampleBytes('good-inventory.xlsx'), 'good-inventory.xlsx', 0);
    const result = analyzeWorkbook(workbook);
    expect(result.sheetCount).toBe(1);
    expect(result.score.total).toBeGreaterThanOrEqual(95);
    expect(result.findings.filter((f) => f.severity === 'high')).toHaveLength(0);
  });

  it('messy-inventory.xlsx triggers the expected quality rules', () => {
    const ids = ruleIds('messy-inventory.xlsx');
    for (const expected of ['R002', 'R003', 'R004', 'R005', 'R006', 'R007', 'R008', 'R014']) {
      expect(ids).toContain(expected);
    }
  });

  it('production-schedule.xlsx has formulas, a merge, a hidden sheet across 2 sheets', () => {
    const workbook = parseXlsx(sampleBytes('production-schedule.xlsx'), 'production-schedule.xlsx', 0);
    const result = analyzeWorkbook(workbook);
    const ids = new Set(result.findings.map((f) => f.ruleId));
    expect(result.sheetCount).toBe(2);
    expect(ids).toContain('R009'); // formula error
    expect(ids).toContain('R011'); // merged cells
    expect(ids).toContain('R012'); // hidden sheet
    expect(result.score.total).toBeLessThan(100);
  });

  it('good-inventory.csv parses and scores highly', () => {
    const buffer = sampleBytes('good-inventory.csv');
    const arrayBuffer = buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength);
    const { text } = decodeCsvBuffer(arrayBuffer as ArrayBuffer);
    const { workbook } = parseCsvText(text, 'good-inventory.csv', buffer.byteLength);
    const result = analyzeWorkbook(workbook);
    expect(result.fileType).toBe('csv');
    expect(result.score.total).toBeGreaterThanOrEqual(95);
  });
});
